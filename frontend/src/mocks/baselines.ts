function generateHistory(mean: number, std: number, count: number, startDaysAgo: number) {
  const points = [];
  const now = new Date('2026-11-15T12:00:00Z');
  for (let i = 0; i < count; i++) {
    const d = new Date(now.getTime() - (startDaysAgo - i) * 86400000);
    // pseudo random variation
    const noise = Math.sin(i * 1.7) * std * 0.9 + Math.cos(i * 0.6) * std * 0.3;
    const val = Number((mean + noise).toFixed(2));
    points.push({
      date: d.toISOString().split('T')[0],
      value: val
    });
  }
  return points;
}

